def sanitize_and_refine_text(markdown_text: str, topic: str = "") -> str:
    """
    6대 품질 정제 엔진:
    1. 미검증 지어내기 / 범용 치환 문장 100% 안전 삭제 (Purge)
    2. 요약성 반복 문단 ('결국', '나아가', '이러한', '종합적으로' 등) 완전 소탕
    3. 과장/선동 어휘 ('절호의 기회', '반드시', '패러다임 전환' 등) 객관적 문체로 자동 순화
    4. 범용 템플릿/부록 섹션 수 전체 글에서 최대 1개로 엄격 제한
    """
    lines = markdown_text.split('\n')
    filtered_lines = []

    # 복붙형 범용 치환문구 패턴 (지어내기 없이 안전 삭제)
    generic_patterns = [
        r"단순한 일시적 이슈나 거품을 넘어",
        r"개인 경제 생태계의 패러다임",
        r"체계적으로 도입한 주체와 그렇지 못한 주체",
        r"특정 전문가나 대기업만의 전유물",
        r"막연한 기대감이나 불안감이 아니라",
        r"새로운 패러다임 수용은 단순한 지식 축적을 넘어",
        r"역사적으로 거대한 패러다임의 변화는 언제나",
        r"글로벌 공급망과 각국의 제도적 규제 완화 기조와도 긴밀하게",
        r"진입 장벽이 한 층 더 낮아질 것으로 전망",
        r"단순 비용 절감.*단기적 유행",
        r"실질적 성과 및 운영 효율성 격차",
        r"체계적 전략이 시장을 주도"
    ]
    generic_regex = re.compile("|".join(generic_patterns))

    # 요약성 반복 문단 시작 키워드
    summary_starter = ("결국 ", "나아가 ", "이러한 ", "종합적으로 ", "결론적으로 ", "역사적으로 ")

    # 과장 어휘 순화 맵
    buzzword_map = {
        "절호의 기회": "주요 고려 요소",
        "반드시": "사전에",
        "패러다임 전환": "기술 및 시장 구조 변화",
        "패러다임": "기술 및 구조",
        "압도적": "상대적",
        "독점적": "기술적",
        "시대를 뒤흔들": "산업 지형에 영향을 줄",
        "폭탄": "변수",
        "비할 수 없이": "상대적으로",
        "거대 거품": "시장 변동성"
    }

    template_section_count = 0

    for line in lines:
        stripped = line.strip()

        # 1. 템플릿/부록 섹션 개수 체크 (최대 1개만 허용)
        if stripped.startswith("## 📌 [부록") or stripped.startswith("## 🚨 치명적") or stripped.startswith("## 👤 페르소나"):
            template_section_count += 1
            if template_section_count > 1:
                continue  # 초과 템플릿 섹션 삭제

        # 2. 범용 복붙형 문장 소탕 (미검증 지어내기 없이 완전 삭제)
        if generic_regex.search(stripped):
            continue

        # 3. 요약성 반복 문단 소탕
        if stripped.startswith(summary_starter):
            continue

        # 4. 과장/선동 어휘 순화
        for bw, replacement in buzzword_map.items():
            if bw in line:
                line = line.replace(bw, replacement)

        filtered_lines.append(line)

    refined_md = "\n".join(filtered_lines)
    # 연속 빈 줄 정리
    refined_md = re.sub(r'\n{3,}', '\n\n', refined_md)
    return refined_md


def generate_hashtags(markdown_text: str, title: str, labels: list = None) -> List[str]:
    valid_tags = set()

    if labels:
        for l in labels:
            clean = str(l).strip().lstrip('#')
            if content_builder.is_valid_topic_hashtag(clean):
                valid_tags.add(clean)

    prompt = f"제목: '{title}'\n\n본문 내용에 기반하여 전문 블로그 주제 해시태그 10개를 작성해줘. 의미없는 조사나 동사(#당신이, #않는 등)는 절대 제외하고, '반도체', '파운드리', 'IT기술', '2026트렌드'처럼 순수 전문 키워드 명사 태그만 쉼표로 구분해서 출력해줘."
    raw_res = _call_gemini_api(prompt, temperature=0.3)

    if raw_res:
        extracted = [w.strip().lstrip('#') for w in raw_res.split(',') if w.strip()]
        for tag in extracted:
            clean = re.sub(r'[^\w가-힣]', '', tag)
            if content_builder.is_valid_topic_hashtag(clean):
                valid_tags.add(clean)

    title_words = [w for w in re.findall(r'[\w가-힣]{2,}', title) if w not in content_builder.KOREAN_STOPWORDS]
    for tw in title_words:
        if content_builder.is_valid_topic_hashtag(tw):
            valid_tags.add(tw)

    defaults = ["IT테크", "반도체기술", "재테크노하우", "2026트렌드", "생활정보", "절약꿀팁", "실전가이드", "정부지원"]
    for d in defaults:
        if len(valid_tags) < 10:
            valid_tags.add(d)

    final_hashtags = [f"#{t}" for t in list(valid_tags)[:12]]
    print(f"  🏷️ 정제된 해시태그 {len(final_hashtags)}개 생성 완료: {', '.join(final_hashtags[:5])}...")
    return final_hashtags


