LAST_API_QUOTA_EXHAUSTED = False


def get_gemini_api_key() -> str:
    return getattr(config, "GOOGLE_API_KEY", "") or os.getenv("GOOGLE_API_KEY", "")


def _call_gemini_api(prompt: str, system_instruction: str = "", temperature: float = 0.3, max_tokens: int = 8192, retries: int = 1) -> str:
    global LAST_API_QUOTA_EXHAUSTED
    api_key = get_gemini_api_key()
    if not api_key:
        return ""

    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-flash-latest:generateContent?key={api_key}"

    parts = []
    if system_instruction:
        parts.append({"text": system_instruction})
    parts.append({"text": prompt})

    payload = {
        "contents": [{"parts": parts}],
        "generationConfig": {
            "temperature": temperature,
            "maxOutputTokens": max_tokens,
        },
    }

    for attempt in range(1, retries + 1):
        try:
            resp = requests.post(url, json=payload, timeout=20)
            if resp.status_code in (429, 403):
                print(f"  ⏳ [gemini-flash-latest] API 429 (Rate Limit). 오프라인/동적 고유 렌더링으로 전환...")
                time.sleep(1)
                LAST_API_QUOTA_EXHAUSTED = True
                return ""

            resp.raise_for_status()
            res_json = resp.json()
            output_text = res_json["candidates"][0]["content"]["parts"][0]["text"].strip()

            if output_text.startswith("```markdown"):
                output_text = output_text[11:].rstrip("`").strip()
            elif output_text.startswith("```"):
                output_text = output_text[3:].rstrip("`").strip()

            LAST_API_QUOTA_EXHAUSTED = False
            return output_text
        except Exception as e:
            time.sleep(1)

    LAST_API_QUOTA_EXHAUSTED = True
    return ""



