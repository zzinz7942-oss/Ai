    cleaned = re.sub(r'\[최종.*\]|2026년 필수 가이드:|보이지 않는 엔진', '', raw_title).strip()

    prompt = f"주제: '{cleaned}'에 대해 블로그 클릭률(CTR)을 극대화할 수 있는 A/B/C 제목 후보 3개를 작성해줘. 각 제목은 숫자, 궁금증 유발, 실질적 이득 표현이 포함되어야 해. 3개 제목 중 가장 강력한 제목 1개만 다른 설명 없이 바로 출력해줘."
